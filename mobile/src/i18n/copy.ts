export const catalogs: Record<LanguageCode, Copy> = { en, ur };

export function copy(language: LanguageCode): Copy {
  return language === 'ur' ? ur : en;
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => key in values ? `\u2068${values[key]}\u2069` : match);
}
